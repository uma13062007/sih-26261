import { apiClient, isMockApiEnabled, simulateDelay } from './apiClient';
import { mockStore } from '../mocks/store';

export const reportService = {
  async getApplicationReport(applicationId) {
    if (isMockApiEnabled()) {
      await simulateDelay(350);
      const app = mockStore.getApplicationById(applicationId);
      if (!app) throw new Error(`Application ${applicationId} not found`);

      const docs = mockStore.getDocuments(applicationId);
      const fields = mockStore.getExtractedFields(applicationId);
      const findings = mockStore.getFindings(applicationId);
      const audit = mockStore.getAuditEvents({ applicationId });

      return {
        data: {
          reportId: `REP-${applicationId}-${Date.now().toString().slice(-4)}`,
          application: app,
          documents: docs,
          extractedFields: fields,
          findings: findings,
          auditHistory: audit,
          generatedAt: new Date().toISOString(),
          generatedBy: (() => { try { return JSON.parse(localStorage.getItem('niyantran_demo_profile') || '{}').officerName || 'Demo Reviewer'; } catch { return 'Demo Reviewer'; } })(),
          disclaimer: 'Synthetic demonstration report generated by the Niyantran prototype. Not an official AICTE assessment, certificate, or sanction order.',
        },
      };
    }
    return apiClient.get(`/applications/${applicationId}/report`);
  },
};
